"""Dev tool: freeze the current models as a migration SQL file.

    python tools/gen_baseline.py database/migrations/0001_baseline.sql

Run it ONCE for the baseline. Later schema changes are hand-written NNNN_*.sql files
(tests/unit/test_schema.py fails if models and migrations drift apart).
"""
import sys
from pathlib import Path

from sqlalchemy import create_engine

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from database.models import Base  # noqa: E402


def main(out: str) -> None:
    engine = create_engine("sqlite://")
    Base.metadata.create_all(engine)
    with engine.connect() as conn:
        rows = conn.exec_driver_sql(
            "SELECT sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY type DESC, name"  # tables before indexes
        ).fetchall()
    Path(out).write_text("-- Baseline schema (generated by tools/gen_baseline.py)\n" + ";\n\n".join(r[0] for r in rows) + ";\n")


if __name__ == "__main__":
    main(sys.argv[1])
